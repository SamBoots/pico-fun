static inline const uint8_t* font8x16_glyph(char a_c)
{
    if (a_c >= '0' && a_c <= '9')
        return font8x16_digits[(uint8_t)(a_c - '0')];
    if (a_c >= 'a' && a_c <= 'z')
        return font8x16_lower[(uint8_t)(a_c - 'a')];
    return (const uint8_t *)0;
}

