static const uint8_t font4x8_blank[4] = { 0, 0, 0, 0 };

static inline const uint8_t* font4x8_glyph(char a_c)
{
    if (a_c >= '0' && a_c <= '9')
        return font4x8_digits[(uint8_t)(a_c - '0')];
    if (a_c >= 'A' && a_c <= 'Z')
        return font4x8_upper[(uint8_t)(a_c - 'A')];
    if (a_c >= 'a' && a_c <= 'z')
        return font4x8_upper[(uint8_t)(a_c - 'a')];
    return font4x8_blank;
}

